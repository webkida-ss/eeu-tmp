// UI localization for the Untangle extension.
//
// The UI locale follows the learner's native (explanation) language, so the
// whole surface — panel, chat, popup, settings — reads in the same language
// as the AI explanations. Loaded after settings.js and before shared.js in
// every context (web page, side panel document, service worker).
//
// Catalog rules:
// - `ja` is the canonical key set; every locale must define every key
//   (enforced by tests). Lookup falls back to `en`, then `ja`.
// - Templates use `{name}` placeholders. Values passed as params must be
//   plain text or pre-escaped HTML; templates themselves may contain markup.

var activeUiLocale = typeof activeUiLocale === 'string' ? activeUiLocale : 'ja';

function setUiLocale(code) {
  const normalized = normalizeLanguageCode(code);
  activeUiLocale = UI_MESSAGES[normalized] ? normalized : 'en';
  return activeUiLocale;
}

function getUiLocale() {
  return activeUiLocale;
}

function t(key, params = null) {
  const catalog = UI_MESSAGES[activeUiLocale] || UI_MESSAGES.en;
  let text = catalog[key] ?? UI_MESSAGES.en[key] ?? UI_MESSAGES.ja[key] ?? key;
  if (params) {
    text = text.replace(/\{(\w+)\}/g, (match, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
    );
  }
  return text;
}

// Translates static DOM annotated with data-i18n / data-i18n-placeholder /
// data-i18n-title attributes (used by sidepanel.html).
function applyDomTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((element) => {
    element.setAttribute('title', t(element.dataset.i18nTitle));
  });
}

